package com.unishut.dto;

import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;

import java.time.LocalDateTime;

/**
 * Data Transfer Object for uniShut reservation information.
 *
 * This DTO is used to transfer reservation data between
 * the backend and the frontend without exposing JPA entities
 * directly.
 *
 * Main reservation flow:
 *
 * Student
 *    |
 *    v
 * Reservation Request
 *    |
 *    v
 * Reservation Service
 *    |
 *    v
 * Reservation Entity
 *    |
 *    v
 * ReservationDTO
 *    |
 *    v
 * Frontend
 */
public class ReservationDTO {

    /**
     * Reservation ID.
     *
     * This is normally generated by the database.
     */
    private Long id;


    /**
     * ID of the student/user making the reservation.
     */
    @NotNull(message = "User ID is required")
    @Positive(message = "User ID must be a positive number")
    private Long userId;


    /**
     * ID of the trip being reserved.
     */
    @NotNull(message = "Trip ID is required")
    @Positive(message = "Trip ID must be a positive number")
    private Long tripId;


    /**
     * Student name.
     *
     * Normally populated in a response DTO.
     */
    private String userName;


    /**
     * Trip route name.
     *
     * Example:
     * Campus ↔ Dhanmondi
     */
    private String routeName;


    /**
     * Bus number.
     *
     * Example:
     * BUS-01
     */
    private String busNumber;


    /**
     * Assigned serial number.
     *
     * Null when the reservation is waitlisted.
     */
    private Integer serialNumber;


    /**
     * Assigned physical seat number.
     *
     * Example:
     * S-12
     *
     * Null when the reservation is waitlisted.
     */
    private String seatNumber;


    /**
     * Position in the waiting queue.
     *
     * Null when the reservation is confirmed.
     */
    private Integer queuePosition;


    /**
     * Reservation status.
     *
     * Expected values:
     *
     * CONFIRMED
     * WAITLISTED
     * BOARDED
     * CANCELLED
     */
    private String status;


    /**
     * Time when the reservation was issued.
     */
    private LocalDateTime issuedAt;


    /**
     * QR boarding value.
     *
     * This is returned only when appropriate.
     */
    private String qr;


    /**
     * Required by Jackson.
     */
    public ReservationDTO() {
    }


    /**
     * Constructor for creating a reservation request.
     *
     * Only userId and tripId are required when a student
     * initially requests a reservation.
     */
    public ReservationDTO(
            Long userId,
            Long tripId
    ) {
        this.userId = userId;
        this.tripId = tripId;
    }


    /**
     * Constructor for creating a complete reservation response.
     */
    public ReservationDTO(
            Long id,
            Long userId,
            Long tripId,
            String userName,
            String routeName,
            String busNumber,
            Integer serialNumber,
            String seatNumber,
            Integer queuePosition,
            String status,
            LocalDateTime issuedAt,
            String qr
    ) {
        this.id = id;
        this.userId = userId;
        this.tripId = tripId;
        this.userName = userName;
        this.routeName = routeName;
        this.busNumber = busNumber;
        this.serialNumber = serialNumber;
        this.seatNumber = seatNumber;
        this.queuePosition = queuePosition;
        this.status = status;
        this.issuedAt = issuedAt;
        this.qr = qr;
    }


    public Long getId() {
        return id;
    }


    public void setId(Long id) {
        this.id = id;
    }


    public Long getUserId() {
        return userId;
    }


    public void setUserId(Long userId) {
        this.userId = userId;
    }


    public Long getTripId() {
        return tripId;
    }


    public void setTripId(Long tripId) {
        this.tripId = tripId;
    }


    public String getUserName() {
        return userName;
    }


    public void setUserName(String userName) {
        this.userName = userName;
    }


    public String getRouteName() {
        return routeName;
    }


    public void setRouteName(String routeName) {
        this.routeName = routeName;
    }


    public String getBusNumber() {
        return busNumber;
    }


    public void setBusNumber(String busNumber) {
        this.busNumber = busNumber;
    }


    public Integer getSerialNumber() {
        return serialNumber;
    }


    public void setSerialNumber(Integer serialNumber) {
        this.serialNumber = serialNumber;
    }


    public String getSeatNumber() {
        return seatNumber;
    }


    public void setSeatNumber(String seatNumber) {
        this.seatNumber = seatNumber;
    }


    public Integer getQueuePosition() {
        return queuePosition;
    }


    public void setQueuePosition(Integer queuePosition) {
        this.queuePosition = queuePosition;
    }


    public String getStatus() {
        return status;
    }


    public void setStatus(String status) {
        this.status = status;
    }


    public LocalDateTime getIssuedAt() {
        return issuedAt;
    }


    public void setIssuedAt(LocalDateTime issuedAt) {
        this.issuedAt = issuedAt;
    }


    public String getQr() {
        return qr;
    }


    public void setQr(String qr) {
        this.qr = qr;
    }
}