package com.unishut.exception;

import com.unishut.dto.ApiResponse;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.http.converter.HttpMessageNotReadableException;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.validation.FieldError;
import org.springframework.web.bind.MethodArgumentNotValidException;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Global exception handler for the uniShut REST API.
 *
 * This class converts application exceptions into consistent
 * JSON responses so that the frontend does not receive raw
 * Java/Spring error responses.
 */
@RestControllerAdvice
public class GlobalExceptionHandler {

    /**
     * Handles resources that cannot be found.
     *
     * Example:
     *
     * User not found
     * Bus not found
     * Trip not found
     */
    @ExceptionHandler(ResourceNotFoundException.class)
    public ResponseEntity<ApiResponse<Void>> handleResourceNotFound(
            ResourceNotFoundException exception
    ) {

        ApiResponse<Void> response = ApiResponse.error(
                exception.getMessage()
        );

        return ResponseEntity
                .status(HttpStatus.NOT_FOUND)
                .body(response);
    }


    /**
     * Handles invalid requests and business-rule violations.
     *
     * Example:
     *
     * Duplicate email
     * Invalid reservation
     * Invalid bus assignment
     */
    @ExceptionHandler(BadRequestException.class)
    public ResponseEntity<ApiResponse<Void>> handleBadRequest(
            BadRequestException exception
    ) {

        ApiResponse<Void> response = ApiResponse.error(
                exception.getMessage()
        );

        return ResponseEntity
                .status(HttpStatus.BAD_REQUEST)
                .body(response);
    }


    /**
     * Handles authentication failures generated by
     * the application service layer.
     */
    @ExceptionHandler(UnauthorizedException.class)
    public ResponseEntity<ApiResponse<Void>> handleUnauthorized(
            UnauthorizedException exception
    ) {

        ApiResponse<Void> response = ApiResponse.error(
                exception.getMessage()
        );

        return ResponseEntity
                .status(HttpStatus.UNAUTHORIZED)
                .body(response);
    }


    /**
     * Handles authorization failures generated by
     * Spring Security's method-level security.
     *
     * Example:
     *
     * STUDENT attempting an ADMIN-only endpoint.
     *
     * HTTP status:
     * 403 FORBIDDEN
     */
    @ExceptionHandler(AccessDeniedException.class)
    public ResponseEntity<ApiResponse<Void>> handleAccessDenied(
            AccessDeniedException exception
    ) {

        ApiResponse<Void> response = ApiResponse.error(
                "You do not have permission to perform this action"
        );

        return ResponseEntity
                .status(HttpStatus.FORBIDDEN)
                .body(response);
    }


    /**
     * Handles @Valid validation failures.
     *
     * Example:
     *
     * email = invalid
     * password = empty
     *
     * The response contains field-specific validation messages.
     */
    @ExceptionHandler(MethodArgumentNotValidException.class)
    public ResponseEntity<ApiResponse<Map<String, String>>>
    handleValidationErrors(
            MethodArgumentNotValidException exception
    ) {

        Map<String, String> errors = new LinkedHashMap<>();

        for (FieldError fieldError :
                exception.getBindingResult().getFieldErrors()) {

            errors.put(
                    fieldError.getField(),
                    fieldError.getDefaultMessage()
            );
        }

        ApiResponse<Map<String, String>> response =
                new ApiResponse<>(
                        false,
                        "Validation failed",
                        errors
                );

        return ResponseEntity
                .status(HttpStatus.BAD_REQUEST)
                .body(response);
    }


    /**
     * Handles malformed JSON request bodies.
     *
     * Example:
     *
     * Missing comma
     * Invalid JSON syntax
     * Invalid JSON data type
     */
    @ExceptionHandler(HttpMessageNotReadableException.class)
    public ResponseEntity<ApiResponse<Void>>
    handleMalformedRequest(
            HttpMessageNotReadableException exception
    ) {

        ApiResponse<Void> response = ApiResponse.error(
                "Invalid request body"
        );

        return ResponseEntity
                .status(HttpStatus.BAD_REQUEST)
                .body(response);
    }


    /**
     * Handles all unexpected exceptions that were not
     * explicitly handled above.
     *
     * The actual exception is not exposed to the frontend
     * because doing so can reveal internal implementation
     * details.
     */
    @ExceptionHandler(Exception.class)
    public ResponseEntity<ApiResponse<Void>>
    handleGenericException(
            Exception exception
    ) {

        ApiResponse<Void> response = ApiResponse.error(
                "An unexpected server error occurred"
        );

        return ResponseEntity
                .status(HttpStatus.INTERNAL_SERVER_ERROR)
                .body(response);
    }
}