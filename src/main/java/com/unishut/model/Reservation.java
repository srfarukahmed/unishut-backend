package com.unishut.model;

import jakarta.persistence.*;

import java.time.LocalDateTime;

/**
 * Represents a student's reservation for a uniShut trip.
 *
 * A reservation connects:
 *
 * User
 *   +
 * Trip
 *   +
 * Seat / Queue
 *   +
 * Boarding QR
 *
 * Reservation states:
 *
 * CONFIRMED
 * WAITLISTED
 * BOARDED
 * CANCELLED
 */
@Entity
@Table(
        name = "reservations",
        indexes = {
                @Index(
                        name = "idx_reservation_user",
                        columnList = "user_id"
                ),
                @Index(
                        name = "idx_reservation_trip",
                        columnList = "trip_id"
                ),
                @Index(
                        name = "idx_reservation_status",
                        columnList = "status"
                ),
                @Index(
                        name = "idx_reservation_issued_at",
                        columnList = "issued_at"
                )
        }
)
public class Reservation {

    /**
     * Primary key.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;


    /**
     * Student/user who made the reservation.
     *
     * The service layer will verify that the user
     * has the STUDENT role before creating a reservation.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(
            name = "user_id",
            nullable = false,
            foreignKey = @ForeignKey(
                    name = "fk_reservation_user"
            )
    )
    private User user;


    /**
     * Trip for which the reservation was made.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(
            name = "trip_id",
            nullable = false,
            foreignKey = @ForeignKey(
                    name = "fk_reservation_trip"
            )
    )
    private Trip trip;


    /**
     * Confirmed seat serial number.
     *
     * Example:
     * 1
     * 2
     * 18
     *
     * Null when the reservation is waitlisted.
     */
    @Column(
            name = "serial_number"
    )
    private Integer serialNumber;


    /**
     * Actual bus seat selected by the student.
     *
     * Example:
     * S-1
     * S-18
     *
     * Null when the reservation is waitlisted.
     */
    @Column(
            name = "seat_number",
            length = 20
    )
    private String seatNumber;


    /**
     * Waiting-list position.
     *
     * Example:
     * 1
     * 2
     * 3
     *
     * Null when the reservation is confirmed.
     */
    @Column(
            name = "queue_position"
    )
    private Integer queuePosition;


    /**
     * Reservation status.
     *
     * Expected values:
     *
     * CONFIRMED
     * WAITLISTED
     * BOARDED
     * CANCELLED
     */
    @Column(
            name = "status",
            nullable = false,
            length = 20
    )
    private String status;


    /**
     * Time when the reservation was issued.
     */
    @Column(
            name = "issued_at",
            nullable = false
    )
    private LocalDateTime issuedAt;


    /**
     * QR value used for boarding.
     *
     * Example:
     *
     * UNISHUT-T3-U1-RES1
     *
     * This value is generated by the service layer.
     */
    @Column(
            name = "qr",
            unique = true,
            length = 255
    )
    private String qr;


    /**
     * Required by JPA.
     */
    public Reservation() {
    }


    /**
     * Constructor for creating a reservation.
     */
    public Reservation(
            User user,
            Trip trip,
            String status
    ) {
        this.user = user;
        this.trip = trip;
        this.status = status;
        this.issuedAt = LocalDateTime.now();
    }


    /**
     * Automatically set issuedAt before inserting
     * a new reservation.
     */
    @PrePersist
    protected void onCreate() {

        if (issuedAt == null) {
            issuedAt = LocalDateTime.now();
        }

        if (status == null || status.isBlank()) {
            status = "WAITLISTED";
        }
    }


    public Long getId() {
        return id;
    }


    public void setId(Long id) {
        this.id = id;
    }


    public User getUser() {
        return user;
    }


    public void setUser(User user) {
        this.user = user;
    }


    public Trip getTrip() {
        return trip;
    }


    public void setTrip(Trip trip) {
        this.trip = trip;
    }


    public Integer getSerialNumber() {
        return serialNumber;
    }


    public void setSerialNumber(Integer serialNumber) {
        this.serialNumber = serialNumber;
    }


    public String getSeatNumber() {
        return seatNumber;
    }


    public void setSeatNumber(String seatNumber) {
        this.seatNumber = seatNumber;
    }


    public Integer getQueuePosition() {
        return queuePosition;
    }


    public void setQueuePosition(Integer queuePosition) {
        this.queuePosition = queuePosition;
    }


    public String getStatus() {
        return status;
    }


    public void setStatus(String status) {
        this.status = status;
    }


    public LocalDateTime getIssuedAt() {
        return issuedAt;
    }


    public void setIssuedAt(LocalDateTime issuedAt) {
        this.issuedAt = issuedAt;
    }


    public String getQr() {
        return qr;
    }


    public void setQr(String qr) {
        this.qr = qr;
    }
}